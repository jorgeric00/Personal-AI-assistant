package com.lifeos.goals;

/**
 * De dónde sale el progreso: BODY (una medida corporal), TRAINING (días de entreno por semana), EXERCISE (mejor peso
 * de un ejercicio), HABIT (porcentaje cumplido de un hábito), MEAL_PLAN (comidas planificadas que se registraron) y
 * CUSTOM (se marca a mano).
 */
public enum GoalKind {
    BODY, TRAINING, EXERCISE, HABIT, MEAL_PLAN, CUSTOM
}
